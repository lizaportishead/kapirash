-- Каталог: креаторы и ролики. Читать может кто угодно, менять — только из панели или секретным ключом.
-- Выполнить один раз в Supabase → SQL Editor.

create table public.creators (
  name text primary key,
  -- Канал на YouTube (без @) и id аватарки оттуда же; пусто — у креатора нет страницы канала и аватарки.
  handle text,
  avatar_id text
);

create table public.videos (
  id text primary key, -- id ролика на YouTube
  title text not null,
  channel text not null references public.creators (name) on update cascade,
  topic text not null default '',
  level text not null default '',
  duration text not null default '',
  -- Порядок в каталоге: новые ролики встают в конец.
  sort integer generated by default as identity
);

alter table public.creators enable row level security;
alter table public.videos enable row level security;
create policy "read" on public.creators for select to anon, authenticated using (true);
create policy "read" on public.videos for select to anon, authenticated using (true);


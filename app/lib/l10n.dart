/// Язык интерфейса: 'ru' или 'en'. Ключи переводов — русские строки, поэтому в коде остаётся русский текст,
/// а [ui] подменяет его английским, когда выбран английский.
String uiLang = 'ru';

bool get isEn => uiLang == 'en';

/// Язык по умолчанию — язык телефона: русскоязычным русский, остальным английский.
String defaultLang() => PlatformDispatcher.instance.locale.languageCode == 'ru' ? 'ru' : 'en';

/// Перевод строки интерфейса; {0}, {1} в строке заменяются на [args].
/// Название приложения: в русской версии кириллицей.
String get brandName => isEn ? 'Kapiraš' : 'Капираш';

String ui(String ru, [List<Object> args = const []]) {
  var s = isEn ? (_en[ru] ?? ru) : ru;
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}

/// Тема каталога. В данных темы русские, на экране — на языке интерфейса.
String topicLabel(String topic) => isEn ? (_topics[topic] ?? topic) : topic;

/// Склонение по числу: в русском три формы, в английском две. Английские слова ищутся по первой форме.
String plural(int n, String one, String few, String many) {
  if (isEn) {
    final e = _plurals[one];
    if (e != null) return n == 1 ? e.$1 : e.$2;
  }
  final d = n % 10, h = n % 100;
  if (d == 1 && h != 11) return one;
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return few;
  return many;
}

/// Описание формы слова, которое хранится по-русски («Родительный падеж, мн. число»), на языке интерфейса.
String formUi(String form) {
  if (!isEn || form.isEmpty) return form;
  var s = form.toLowerCase();
  final keys = _forms.keys.toList()..sort((a, b) => b.length.compareTo(a.length));
  for (final k in keys) {
    s = s.replaceAll(k, _forms[k]!);
  }
  return s[0].toUpperCase() + s.substring(1);
}


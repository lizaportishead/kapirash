import 'store.dart';

class Video {
  const Video({
    required this.id,
    required this.title,
    required this.channel,
    this.topic = '',
    this.level = '',
    this.duration = '',
    this.kind = '',
    this.audio = '',
    this.mine = false,
  });
  final String id, title, channel, topic, level, duration;

  /// Откуда ролик: пусто — YouTube, 'tiktok' — вертикальный клип из TikTok, 'podcast' — эпизод подкаста.
  final String kind;

  /// Прямая ссылка на mp3 эпизода подкаста; у остальных пусто.
  final String audio;

  int get views => _ytViews[id] ?? 0;
  bool get tiktok => kind == 'tiktok';
  bool get podcast => kind == 'podcast';

  /// Страница клипа в TikTok; имя автора в адресе не обязательно.
  String get tiktokUrl => 'https://www.tiktok.com/@_/video/$id';

  /// Ролик добавил сам пользователь: его нет в каталоге, а субтитры лежат на устройстве.
  final bool mine;

  static Video fromJson(Map<String, dynamic> j) => Video(
    id: j['id'],
    title: j['title'],
    channel: j['channel'],
    topic: j['topic'] ?? '',
    level: j['level'] ?? '',
    duration: j['duration'] ?? '',
    kind: j['kind'] ?? '',
    audio: j['audio'] ?? '',
  );
}

